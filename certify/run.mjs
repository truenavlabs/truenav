// Score the demo funds with the engine, build one certificate per fund and sign it.
//
//   node certify/run.mjs --fixture            write contract/tests/fixtures/engine-certificates.json,
//                                             signed with the fixed throwaway test key the Rust tests use
//   node certify/run.mjs --out <file>         sign with a fresh throwaway key kept in .keys/ (gitignored)
//     [--contract <id>] [--accounts <json>]   contract account id and fund_id -> account map
//
// The fixed test key is 32 bytes of 0x07. It exists only for the offline check; it holds no value and is
// not a NEAR account key. A fresh key from newSecretKey() is used for anything else.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";
import { scorePortfolio } from "../engine/src/score.mjs";
import { toCertificate, signCertificate, addressOf, newSecretKey } from "./certificate.mjs";

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const opt = (name, dflt) => (args.includes(name) ? args[args.indexOf(name) + 1] : dflt);

const root = new URL("../", import.meta.url);
const fx = JSON.parse(readFileSync(new URL("spec/nav/fixtures.json", root), "utf8"));

const fixtureMode = flag("--fixture");
const contractId = opt("--contract", "registry.test.near");
const accounts = JSON.parse(
  opt("--accounts", JSON.stringify({ admin: "alice.near", servicer: "bob.near", "harbor-credit-fund": "charlie.near", "meridian-yield-fund": "danny.near" })),
);

let engineCommit = "fixture";
if (!fixtureMode) {
  try {
    engineCommit = execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    engineCommit = "unknown";
  }
}

let secretKey;
if (fixtureMode) secretKey = new Uint8Array(32).fill(7);
else {
  const keyFile = new URL(".keys/certify-signer.json", root);
  if (existsSync(keyFile)) secretKey = Uint8Array.from(Buffer.from(JSON.parse(readFileSync(keyFile, "utf8")).secret_hex, "hex"));
  else {
    secretKey = newSecretKey();
    mkdirSync(new URL(".keys/", root), { recursive: true });
    writeFileSync(keyFile, JSON.stringify({ note: "throwaway testnet certificate signer; never commit", secret_hex: Buffer.from(secretKey).toString("hex") }), { mode: 0o600 });
  }
}

const nowMs = Date.parse(fx.valuation_time);
const results = scorePortfolio({ pd: fx.pd, lgd: fx.lgd }, fx.funds, { now: fx.valuation_time, certStore: fx.cert_store });
const certificates = results.map((r) => {
  const certificate = toCertificate(r, { fund_account: accounts[r.fundId], manager_id: r.managerId }, { nowMs, engineCommit });
  return { certificate, signature: signCertificate(contractId, certificate, secretKey), raw: Math.round(r.raw * 100) / 100 };
});

const out = {
  note: fixtureMode
    ? "Generated by node certify/run.mjs --fixture. Signed with the fixed throwaway test key (32 bytes of 0x07). Read by contract/tests/engine_certificates.rs."
    : "Signed with a throwaway testnet key kept in .keys/.",
  contract_id: contractId,
  signer_address: addressOf(secretKey),
  admin: accounts.admin,
  servicer: accounts.servicer,
  funds: results.map((r) => ({ fund_id: r.fundId, account_id: accounts[r.fundId], manager_id: r.managerId })),
  certificates,
};

const outPath = fixtureMode ? new URL("contract/tests/fixtures/engine-certificates.json", root) : new URL(opt("--out", "out/certificates.json"), root);
mkdirSync(new URL(".", outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
for (const c of certificates) {
  console.log(`${c.certificate.fund_id}: ${c.certificate.status} ${c.certificate.score ?? "no number"} ${c.certificate.band} (raw ${c.raw})`);
}
console.log(`signer ${out.signer_address}`);
console.log(`wrote ${outPath.pathname}`);
